#!/usr/bin/env python3
"""Regenerates X32Remote.swiftpm/Core/SceneNodes.swift from X32ds_node.h (pmaillot/X32-Behringer).
Usage: python3 tools/gen-scene-nodes.py path/to/X32ds_node.h"""
import re, sys
s = open(sys.argv[1]).read()
i = s.index('char* sc_node[]'); j = s.index('};', i)
nodes = re.findall(r'"([^"]+)"', s[i:j])
body = "\n".join(nodes)
out = ('// Generated by tools/gen-scene-nodes.py from Patrick-Gilles Maillot\'s X32 tools (X32ds_node.h):\n'
       '// the nodes that make up an X32 scene, in the order a scene file lists them.\n'
       'enum SceneNodes {\n    static let all: [String] = raw.split(separator: "\\n").map(String.init)\n\n'
       '    private static let raw = """\n' + body + '\n"""\n}\n')
open('X32Remote.swiftpm/Core/SceneNodes.swift', 'w').write(out)
print(len(nodes), "nodes")
