#!/usr/bin/env python3
"""Generates X32Remote.swiftpm/Core/EffectsCatalog.swift from the effect parameter tables in the
x32-osc npm package (MIT, Mark Schwartzkopf: https://github.com/markschwartzkopf/x32-osc).

The JavaScript is read as text and converted to JSON; it is never executed.
Usage: tools/gen-fx-catalog.py path/to/x32definitions.js > X32Remote.swiftpm/Core/EffectsCatalog.swift
"""
import json, re, sys

src = open(sys.argv[1]).read()
start = src.index("var x32FxConditional = {")
end = src.index("\n};", start) + 3
body = src[start + len("var x32FxConditional = "):end - 1].strip()
for name in ["delayFactor", "dlyPattern", "pq5MidFreq", "cmbRatio"]:
    body = body.replace("x32Enums." + name, re.search(r"\b" + name + r": (\[[^\]]*\])", src).group(1))
assert "x32Enums" not in body and "function" not in body
body = re.sub(r"([{,]\s*)'([^']+)'\s*:", r'\1"\2":', body)
body = re.sub(r"([{,]\s*)([A-Za-z_][A-Za-z0-9_]*)\s*:", r'\1"\2":', body)
body = re.sub(r"'((?:[^'\\]|\\.)*)'", lambda m: json.dumps(m.group(1)), body)
body = re.sub(r",(\s*[}\]])", r"\1", body)
tables = json.loads(body)

def swift_str(s):
    return json.dumps(s)

def num(x):
    x = float(x)
    return repr(x) if x != int(x) else repr(int(x)) + ".0"

def unit(p):
    """Units only where the name and range leave no doubt."""
    name = p["_name"].lower()
    lo, hi = float(p.get("_min", 0)), float(p.get("_max", 0))
    if p.get("_freq") or (("freq" in name or "cut" in name) and lo >= 1):
        return "Hz"
    if ("gain" in name or "level" in name) and lo < 0:
        return "dB"
    if name == "pre delay":
        return "ms"
    if name == "decay" and hi <= 30:
        return "s"
    if name == "mix" and lo == 0 and hi == 100:
        return "%"
    return ""

def decimals(p):
    if "_decimals" in p:
        return int(p["_decimals"])
    step = p.get("_step")
    if step is not None and float(step) != int(float(step)):
        return len(repr(float(step)).split(".")[1])
    return 0

out = []
out.append("// Generated by tools/gen-fx-catalog.py from the x32-osc package's effect tables")
out.append("// (MIT licence, Mark Schwartzkopf). Do not edit by hand.")
out.append("// Wire types (int choices vs float values) were checked against Patrick-Gilles Maillot's X32")
out.append("// emulator; the few types where the two sources disagree are left out of `Effects.parameters`.")
out.append("")
out.append("extension Effects {")
out.append("    static let catalog: [String: [Param]] = [")
for code, params in tables.items():
    out.append(f"        {swift_str(code)}: catalogParams([")
    for p in params:
        if p["_type"] == "enum":
            opts = ", ".join(swift_str(o) for o in p["_enum"])
            out.append(f"            ({swift_str(p['_name'])}, .choice([{opts}])),")
        else:
            lo, hi = p["_min"], p["_max"]
            if p["_type"] == "linear":
                steps = round((float(hi) - float(lo)) / float(p["_step"]))
                scale = f".linear({num(lo)}, {num(hi)})"
            else:
                steps = int(p["_steps"])
                scale = f".logarithmic({num(lo)}, {num(hi)})"
            out.append(f"            ({swift_str(p['_name'])}, .value(ParamSpec({scale}, steps: {steps}, unit: {swift_str(unit(p))}, "
                       f"decimals: {decimals(p)}, defaultNorm: 0.5))),")
    out.append("        ]),")
out.append("    ]")
out.append("")
out.append("    private static func catalogParams(_ list: [(String, Param.Kind)]) -> [Param] {")
out.append("        list.enumerated().map { Param(number: $0.offset + 1, name: $0.element.0, kind: $0.element.1) }")
out.append("    }")
out.append("}")
print("\n".join(out))
